CALCULATOR_SOURCE = '''"""Deterministic calculator generated by the Scheduling Agent POC."""


def add(left: float, right: float) -> float:
    return left + right


def subtract(left: float, right: float) -> float:
    return left - right


def multiply(left: float, right: float) -> float:
    return left * right


def divide(left: float, right: float) -> float:
    if right == 0:
        raise ValueError("division by zero")
    return left / right
'''

TASK_A_ITEMS = (1, 2, 3, 4)
TASK_A_STEP_DELAY_SECONDS = 0.12


def _task_a_prepare_item(item: int) -> tuple[int, ...]:
    prepared_values = (item, item + 1, item + 2)
    time.sleep(TASK_A_STEP_DELAY_SECONDS)
    return prepared_values


def _task_a_transform_item(prepared_values: tuple[int, ...]) -> int:
    transformed_value = sum(value**2 for value in prepared_values)
    time.sleep(TASK_A_STEP_DELAY_SECONDS)
    return transformed_value


def _task_a_generate_report(item: int, transformed_value: int) -> str:
    status = "even" if transformed_value % 2 == 0 else "odd"
    report = f"item={item}, result={transformed_value}, status={status}"
    time.sleep(TASK_A_STEP_DELAY_SECONDS)
    return report


def task_a():
    print(f"[{datetime.now().strftime('%H:%M:%S')}] Task A BATCH START")
    for item in TASK_A_ITEMS:
        prepared_values = _task_a_prepare_item(item)
        print(f"{item}-A prepared={prepared_values}")

        transformed_value = _task_a_transform_item(prepared_values)
        print(f"{item}-B transformed={transformed_value}")

        report = _task_a_generate_report(item, transformed_value)
        print(f"{item}-C report={report}")
    print(f"[{datetime.now().strftime('%H:%M:%S')}] Task A BATCH END")


TASK_B_STEP_DELAY_SECONDS = 0.9
TASK_B_CUSTOMER_RECORDS = (
    ("customer-101", "north", True, 120),
    ("customer-102", "south", False, 80),
    ("customer-103", "north", True, 200),
    ("customer-104", "west", True, 150),
)


def _task_b_load_records() -> tuple[tuple[str, str, bool, int], ...]:
    records = tuple(TASK_B_CUSTOMER_RECORDS)
    time.sleep(TASK_B_STEP_DELAY_SECONDS)
    return records


def _task_b_filter_records(
    records: tuple[tuple[str, str, bool, int], ...],
) -> tuple[tuple[str, str, bool, int], ...]:
    active_records = tuple(record for record in records if record[2])
    time.sleep(TASK_B_STEP_DELAY_SECONDS)
    return active_records


def _task_b_aggregate_records(
    records: tuple[tuple[str, str, bool, int], ...],
) -> tuple[int, tuple[tuple[str, int], ...]]:
    total_value = sum(record[3] for record in records)
    regions = sorted({record[1] for record in records})
    region_totals = tuple(
        (region, sum(record[3] for record in records if record[1] == region))
        for region in regions
    )
    time.sleep(TASK_B_STEP_DELAY_SECONDS)
    return total_value, region_totals


def _task_b_generate_summary(
    record_count: int,
    total_value: int,
    region_totals: tuple[tuple[str, int], ...],
) -> str:
    summary = (
        f"active_customers={record_count}, total_value={total_value}, "
        f"region_totals={region_totals}"
    )
    time.sleep(TASK_B_STEP_DELAY_SECONDS)
    return summary


def task_b():
    print(f"[{datetime.now().strftime('%H:%M:%S')}] Task B START")
    records = _task_b_load_records()
    print(f"B-LOAD records={len(records)}")

    active_records = _task_b_filter_records(records)
    print(f"B-FILTER active_records={len(active_records)}")

    total_value, region_totals = _task_b_aggregate_records(active_records)
    print(f"B-AGGREGATE total_value={total_value}, regions={region_totals}")

    summary = _task_b_generate_summary(
        len(active_records), total_value, region_totals
    )
    print(f"B-SUMMARY {summary}")
    print(f"[{datetime.now().strftime('%H:%M:%S')}] Task B END")


TASK_C_STEP_DELAY_SECONDS = 0.38
TASK_C_REPORT_RECORDS = (
    ("report-201", 110, 100),
    ("report-202", 88, 100),
    ("report-203", 103, 100),
)


def _task_c_load_records() -> tuple[tuple[str, int, int], ...]:
    records = tuple(TASK_C_REPORT_RECORDS)
    time.sleep(TASK_C_STEP_DELAY_SECONDS)
    return records


def _task_c_calculate(record: tuple[str, int, int]) -> tuple[int, float]:
    _, actual, target = record
    variance = actual - target
    variance_percent = round((variance / target) * 100, 2)
    time.sleep(TASK_C_STEP_DELAY_SECONDS)
    return variance, variance_percent


def _task_c_classify(variance_percent: float) -> str:
    if variance_percent >= 10:
        classification = "above_target"
    elif variance_percent <= -10:
        classification = "below_target"
    else:
        classification = "on_target"
    time.sleep(TASK_C_STEP_DELAY_SECONDS)
    return classification


def _task_c_generate_result(
    report_id: str,
    variance: int,
    variance_percent: float,
    classification: str,
) -> str:
    result = (
        f"report={report_id}, variance={variance}, "
        f"variance_percent={variance_percent:.2f}, class={classification}"
    )
    time.sleep(TASK_C_STEP_DELAY_SECONDS)
    return result


def task_c():
    print(f"[{datetime.now().strftime('%H:%M:%S')}] Task C START")
    records = _task_c_load_records()
    print(f"C-LOAD records={len(records)}")

    for record in records:
        report_id = record[0]
        variance, variance_percent = _task_c_calculate(record)
        print(
            f"{report_id}-CALCULATE variance={variance}, "
            f"variance_percent={variance_percent:.2f}"
        )

        classification = _task_c_classify(variance_percent)
        print(f"{report_id}-CLASSIFY class={classification}")

        result = _task_c_generate_result(
            report_id, variance, variance_percent, classification
        )
        print(f"{report_id}-REPORT {result}")
    print(f"[{datetime.now().strftime('%H:%M:%S')}] Task C END")


TASKS = {
    "A": task_a,
    "B": task_b,
    "C": task_c,
}


def schedule_interval_task(task_name: str, seconds: int) -> str:
    """Schedule one of the predefined tasks at a recurring interval."""

    task_name = task_name.upper()

    if task_name not in TASKS:
        return f"Unknown task: {task_name}. Available tasks: A, B, C."

    if seconds <= 0:
        return "Interval must be greater than 0 seconds."

    job_id = f"task_{task_name}"

    scheduler.add_job(
        TASKS[task_name],
        trigger="interval",
        seconds=seconds,
        id=job_id,
        replace_existing=True,
        max_instances=1,
    )

    return f"Task {task_name} scheduled every {seconds} seconds."


def _workflow_paths(project_root: Path | None = None) -> tuple[Path, Path, Path]:
    root = project_root or PROJECT_ROOT
    generated_dir = root / "generated"
    history_path = root / "logs" / "history.log"
    return generated_dir / "calculator.py", generated_dir / "README.md", history_path


def calculator_workflow_task_a(project_root: Path | None = None) -> str:
    """Create the deterministic calculator source file."""

    calculator_path, _, _ = _workflow_paths(project_root)
    calculator_path.parent.mkdir(parents=True, exist_ok=True)
    calculator_path.write_text(CALCULATOR_SOURCE, encoding="utf-8")
    return "generated/calculator.py created"


def calculator_workflow_task_b(project_root: Path | None = None) -> str:
    """Load the generated calculator and verify all required behavior."""

    calculator_path, _, _ = _workflow_paths(project_root)
    if not calculator_path.is_file():
        raise FileNotFoundError("generated/calculator.py does not exist")

    calculator = runpy.run_path(str(calculator_path))
    checks = (
        ("add", calculator["add"](2, 3), 5),
        ("subtract", calculator["subtract"](10, 4), 6),
        ("multiply", calculator["multiply"](3, 7), 21),
        ("divide", calculator["divide"](10, 2), 5),
    )
    for name, actual, expected in checks:
        if actual != expected:
            raise AssertionError(f"{name} returned {actual!r}, expected {expected!r}")

    try:
        calculator["divide"](1, 0)
    except ValueError:
        pass
    else:
        raise AssertionError("divide by zero did not raise ValueError")

    return "5/5 calculator checks passed"


