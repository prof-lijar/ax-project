def _concise_error(error: Exception) -> str:
    detail = " ".join(str(error).split()) or "no error detail"
    return f"{type(error).__name__}: {detail}"[:200]


def _append_calculator_history(
    *,
    scheduled_time: datetime,
    actual_start: datetime,
    completed: datetime,
    duration_seconds: float,
    task_results: dict[str, str],
    final_status: str,
    project_root: Path | None = None,
) -> Path:
    _, _, history_path = _workflow_paths(project_root)
    history_path.parent.mkdir(parents=True, exist_ok=True)
    scheduled_kst = scheduled_time.astimezone(SEOUL_TIMEZONE)
    lines = (
        "--------------------------------------------------",
        "Scheduled workflow: calculator",
        f"Scheduled time: {scheduled_kst:%Y-%m-%d %H:%M:%S} {SEOUL_TIMEZONE_NAME}",
        f"Actual start: {actual_start:%Y-%m-%d %H:%M:%S %Z}",
        f"Task A: {task_results['A']}",
        f"Task B: {task_results['B']}",
        f"Task C: {task_results['C']}",
        f"Duration: {duration_seconds:.2f} seconds",
        f"Final status: {final_status}",
        f"Completed: {completed:%Y-%m-%d %H:%M:%S %Z}",
        "--------------------------------------------------",
    )
    with history_path.open("a", encoding="utf-8") as history_file:
        history_file.write("\n".join(lines) + "\n")
    return history_path


def run_calculator_workflow(
    scheduled_time: datetime,
    project_root: Path | None = None,
) -> str:
    """Run calculator Tasks A -> B -> C and always append execution history."""

    scheduled_kst = scheduled_time.astimezone(SEOUL_TIMEZONE)
    actual_start = datetime.now(SEOUL_TIMEZONE)
    started = time.perf_counter()
    task_results = {
        "A": "NOT RUN - workflow stopped before Task A",
        "B": "NOT RUN - dependency did not complete",
        "C": "NOT RUN - dependency did not complete",
    }
    current_task = "A"
    final_status = "FAILURE"

    print(f"[{actual_start:%H:%M:%S}] Calculator workflow START")
    try:
        task_a_result = calculator_workflow_task_a(project_root)
        task_results["A"] = f"SUCCESS - {task_a_result}"
        print(f"Task A: {task_results['A']}")

        current_task = "B"
        task_b_result = calculator_workflow_task_b(project_root)
        task_results["B"] = f"SUCCESS - {task_b_result}"
        print(f"Task B: {task_results['B']}")

        current_task = "C"
        task_c_result = calculator_workflow_task_c(task_b_result, project_root)
        task_results["C"] = f"SUCCESS - {task_c_result}"
        print(f"Task C: {task_results['C']}")
        final_status = "SUCCESS"
    except Exception as error:
        task_results[current_task] = f"FAILURE - {_concise_error(error)}"
        print(f"Task {current_task}: {task_results[current_task]}")
    finally:
        completed = datetime.now(SEOUL_TIMEZONE)
        duration_seconds = time.perf_counter() - started
        history_path = _append_calculator_history(
            scheduled_time=scheduled_kst,
            actual_start=actual_start,
            completed=completed,
            duration_seconds=duration_seconds,
            task_results=task_results,
            final_status=final_status,
            project_root=project_root,
        )
        print(f"History appended: {history_path}")
        print(f"[{completed:%H:%M:%S}] Calculator workflow END - {final_status}")

    return f"Calculator workflow completed with status: {final_status}."


def schedule_calculator_workflow(
    run_at: datetime,
    timezone_name: str,
) -> str:
    """Schedule the calculator workflow once at an exact Asia/Seoul time."""

    if timezone_name != SEOUL_TIMEZONE_NAME:
        raise ValueError(f"Unsupported timezone: {timezone_name}")

    if run_at.tzinfo is None or run_at.utcoffset() is None:
        run_at_kst = run_at.replace(tzinfo=SEOUL_TIMEZONE)
    else:
        run_at_kst = run_at.astimezone(SEOUL_TIMEZONE)

    trigger = DateTrigger(run_date=run_at_kst, timezone=SEOUL_TIMEZONE)
    scheduler.add_job(
        run_calculator_workflow,
        trigger=trigger,
        kwargs={"scheduled_time": run_at_kst},
        id=CALCULATOR_WORKFLOW_JOB_ID,
        replace_existing=True,
        max_instances=1,
    )

    return (
        "Calculator workflow scheduled once for "
        f"{run_at_kst:%Y-%m-%d %H:%M:%S} {SEOUL_TIMEZONE_NAME}."
    )


def _worker_artifact_path(project_root: Path | None = None) -> Path:
    root = project_root or PROJECT_ROOT
    return root / "generated" / "worker_result.json"


def _append_worker_history(
    *,
    scheduled_time: datetime,
    actual_start: datetime,
    completed: datetime,
    invocation_status: str,
    validation_status: str,
    artifact_status: str,
    final_status: str,
    error_detail: str | None = None,
    project_root: Path | None = None,
) -> Path:
    _, _, history_path = _workflow_paths(project_root)
    history_path.parent.mkdir(parents=True, exist_ok=True)
    scheduled_kst = scheduled_time.astimezone(SEOUL_TIMEZONE)
    lines = [
        "--------------------------------------------------",
        "Scheduled workflow: worker_agent",
        f"Scheduled time: {scheduled_kst:%Y-%m-%d %H:%M:%S} {SEOUL_TIMEZONE_NAME}",
        f"Actual start: {actual_start:%Y-%m-%d %H:%M:%S %Z}",
        f"Worker Agent: {WORKER_AGENT_NAME}",
        f"Agent invocation: {invocation_status}",
        f"Structured output validation: {validation_status}",
        f"Artifact: {artifact_status}",
    ]
    if error_detail is not None:
        lines.append(f"Error: {error_detail}")
    lines.extend(
        [
            f"Final status: {final_status}",
            f"Completed: {completed:%Y-%m-%d %H:%M:%S %Z}",
            "--------------------------------------------------",
        ]
    )
    with history_path.open("a", encoding="utf-8") as history_file:
        history_file.write("\n".join(lines) + "\n")
    return history_path


def run_worker_agent_workflow(
    scheduled_time: datetime,
    project_root: Path | None = None,
) -> str:
    """Invoke the Worker Agent, persist its validated result, and log the run."""

    scheduled_kst = scheduled_time.astimezone(SEOUL_TIMEZONE)
    actual_start = datetime.now(SEOUL_TIMEZONE)
    invocation_status = "FAILURE"
    validation_status = "NOT RUN"
    artifact_status = "NOT WRITTEN"
    final_status = "FAILURE"
    error_detail = None

    print(f"[{actual_start:%H:%M:%S}] WORKER AGENT STARTED")
    try:
        worker_result = asyncio.run(run_worker_agent())
        invocation_status = "SUCCESS"
        validation_status = "SUCCESS"
        print("WORKER AGENT COMPLETED")

        completed = datetime.now(SEOUL_TIMEZONE)
        artifact_path = _worker_artifact_path(project_root)
        artifact_path.parent.mkdir(parents=True, exist_ok=True)
        artifact_payload = {
            "worker_agent_name": WORKER_AGENT_NAME,
            "scheduled_time": scheduled_kst.isoformat(),
            "actual_invocation_time": actual_start.isoformat(),
            "structured_result": worker_result.model_dump(mode="json"),
            "final_status": "SUCCESS",
            "completed_time": completed.isoformat(),
        }
        artifact_path.write_text(
            json.dumps(artifact_payload, indent=2) + "\n",
            encoding="utf-8",
        )
        artifact_status = "generated/worker_result.json"
        final_status = "SUCCESS"
        print(f"Artifact written: {artifact_path}")
    except WorkerResultValidationError as error:
        invocation_status = "SUCCESS"
        validation_status = "FAILURE"
        error_detail = _concise_error(error)
        print(f"WORKER AGENT FAILED - {error_detail}")
    except Exception as error:
        error_detail = _concise_error(error)
        print(f"WORKER AGENT FAILED - {error_detail}")
    finally:
        completed = datetime.now(SEOUL_TIMEZONE)
        history_path = _append_worker_history(
            scheduled_time=scheduled_kst,
            actual_start=actual_start,
            completed=completed,
            invocation_status=invocation_status,
            validation_status=validation_status,
            artifact_status=artifact_status,
            final_status=final_status,
            error_detail=error_detail,
            project_root=project_root,
        )
        print(f"History appended: {history_path}")

    return f"Worker Agent workflow completed with status: {final_status}."


def schedule_worker_agent_workflow(
    run_at: datetime,
    timezone_name: str,
) -> str:
    """Schedule the independent Worker Agent workflow once in Asia/Seoul."""

    if timezone_name != SEOUL_TIMEZONE_NAME:
        raise ValueError(f"Unsupported timezone: {timezone_name}")

    if run_at.tzinfo is None or run_at.utcoffset() is None:
        run_at_kst = run_at.replace(tzinfo=SEOUL_TIMEZONE)
    else:
        run_at_kst = run_at.astimezone(SEOUL_TIMEZONE)

    trigger = DateTrigger(run_date=run_at_kst, timezone=SEOUL_TIMEZONE)
    scheduler.add_job(
        run_worker_agent_workflow,
        trigger=trigger,
        kwargs={"scheduled_time": run_at_kst},
        id=WORKER_AGENT_WORKFLOW_JOB_ID,
        replace_existing=True,
        max_instances=1,
    )
    print(
        "WORKER JOB REGISTERED: "
        f"{WORKER_AGENT_WORKFLOW_JOB_ID} at {run_at_kst.isoformat()}"
    )

    return (
        "Worker Agent workflow scheduled once for "
        f"{run_at_kst:%Y-%m-%d %H:%M:%S} {SEOUL_TIMEZONE_NAME}."
    )
